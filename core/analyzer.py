'''用于智能分析、综合评估'''

from models import 每日记录
from config import 时间配置

# 分析判断模块
def 智能分析(记录: 每日记录, 配置: 时间配置 = 时间配置()):
    """根据配置阈值，分析每日记录并给出评估。"""
    print('\n=== 智能评估 ===')
    # 基础条件判断
    if 记录.睡眠 < 配置.睡眠不足阈值:
        print('⚠️  睡眠不足，要注意休息！')
    elif 记录.睡眠 > 配置.睡眠过长阈值:
        print('💤 睡眠充足，但可能过长了')
    else:
        print('✅ 睡眠时长很健康')
        
    # 复合条件判断
    if 配置.学习不足阈值 <= 记录.学习 < 配置.学习达标阈值:
        print('🐢 学习节奏稳健，继续保持！')
    elif 记录.学习 >= 配置.学习充足阈值:
        print('🚀 今天很投入呢！')
    else:
        print('📚 哪怕15分钟也是进步')
        
    # 娱乐时间智能建议
    if 记录.娱乐 < 配置.娱乐达标阈值:
        print('🎯 娱乐时间节制，可适当增加')
    elif 记录.娱乐 > 配置.娱乐过长阈值:
        print('⚠️  娱乐时间偏多，明天可以调整一下节奏')
    else:
        print('✅ 娱乐时间适中，生活需要这样的调剂')
        
    # 运动时间评估
    if 记录.运动 == 配置.运动不足阈值:
        print('💤 今天没有运动，记得身体是革命的本钱')
    elif 记录.运动 < 配置.运动达标阈值:
        print('🏃‍♂️ 有运动意识很棒，可以慢慢增加时长')
    elif 记录.运动 > 配置.运动过度阈值:
        print('🔥 运动达人！注意不要过度疲劳')
    else:
        print('💪 运动习惯很好，继续保持')
    
# 综合评估 - 你的第一个“AI”逻辑
def 综合评估(记录: 每日记录, 配置: 时间配置 = 时间配置()):
    print(f'\n=== 🌈 整体状态分析 ===')
    
    if 记录.睡眠 > 配置.睡眠不足阈值 and 记录.学习 > 配置.学习达标阈值 and 记录.运动 > 配置.运动达标阈值: 
        print('🚀 今日状态爆表！学习、运动、休息的黄金三角')
        print('   就像螺旋楼梯，每个台阶都坚实有力')

    elif 记录.学习 <= 配置.学习不足阈值:
        print('🌱 今天没有编码？没关系，休息也是前进的一部分')
        print('   螺旋成长允许暂时的平台期')
        
    else:
        print('📊 状态有起有落，这才是真实的成长轨迹')
        print('   记住：节奏感比单日表现更重要')

# 能量守恒的趣味检查
def 能量守恒检查(剩余时间):
    print('\n=== 剩余时间检查 ===')
    if 剩余时间 > 10:
        print(f'🔍 发现时间黑洞：有 {abs(剩余时间):.1f} 小时不知去向')
        print('⚠️  就像流体力学, 能量也需要平衡哦!\n')
    else:
        print(f'✅ 剩余{abs(剩余时间):.1f}小时，时间账目清晰，能量分配合理\n')