'''用于智能分析、综合评估'''

from models import 每日记录
from config import 时间配置

# 分析判断模块
def 智能分析(记录: 每日记录, 配置: 时间配置 = 时间配置()) -> list:
    """根据配置阈值，分析每日记录并给出评估。"""
    """将原本的 print 改为返回分析列表"""
    result = []

    # 基础条件判断
    if 记录.睡眠 < 配置.睡眠不足阈值:
        result.append('⚠️  睡眠不足，要注意休息！')
    elif 记录.睡眠 > 配置.睡眠过长阈值:
        result.append('💤 睡眠充足，但可能过长了')
    else:
        result.append('✅ 睡眠时长很健康')
        
    # 复合条件判断
    if 配置.学习不足阈值 <= 记录.学习 < 配置.学习达标阈值:
        result.append('🐢 学习节奏稳健，继续保持！')
    elif 记录.学习 >= 配置.学习充足阈值:
        result.append('🚀 今天很投入呢！')
    else:
        result.append('📚 哪怕15分钟也是进步')
        
    # 娱乐时间智能建议
    if 记录.娱乐 < 配置.娱乐达标阈值:
        result.append('🎯 娱乐时间节制，可适当增加')
    elif 记录.娱乐 > 配置.娱乐过长阈值:
        result.append('⚠️  娱乐时间偏多，明天可以调整一下节奏')
    else:
        result.append('✅ 娱乐时间适中，生活需要这样的调剂')
        
    # 运动时间评估
    if 记录.运动 == 配置.运动不足阈值:
        result.append('💤 今天没有运动，记得身体是革命的本钱')
    elif 记录.运动 < 配置.运动达标阈值:
        result.append('🏃‍♂️ 有运动意识很棒，可以慢慢增加时长')
    elif 记录.运动 > 配置.运动过度阈值:
        result.append('🔥 运动达人！注意不要过度疲劳')
    else:
        result.append('💪 运动习惯很好，继续保持')

    return result
    
# 综合评估 - 你的第一个“AI”逻辑
def 综合评估(记录: 每日记录, 配置: 时间配置 = 时间配置()) -> str:
    """返回整体状态字符串"""
    
    if 记录.睡眠 > 配置.睡眠不足阈值 and 记录.学习 > 配置.学习达标阈值 and 记录.运动 > 配置.运动达标阈值: 
        return '🚀 今日状态爆表！学习、运动、休息的黄金三角，就像螺旋楼梯，每个台阶都坚实有力'

    elif 记录.学习 <= 配置.学习不足阈值:
        return '🌱 今天没有编码？没关系，休息也是前进的一部分，螺旋成长允许暂时的平台期'
    else:
        return '📊 状态有起有落，这才是真实的成长轨迹。记住：节奏感比单日表现更重要'

# 能量守恒的趣味检查
def 能量守恒检查(剩余时间: float) -> str:
    """返回能量守恒检查结果"""

    if 剩余时间 > 10:
        return f'🔍 发现时间黑洞：有 {abs(剩余时间):.1f} 小时不知去向。就像流体力学, 能量也需要平衡哦！'
    else:
        return f'✅ 剩余{abs(剩余时间):.1f}小时，时间账目清晰，能量分配合理'