'''用于输入验证与获取'''
# 输入和验证模块
def 验证用户输入(提示信息):
    while True:
        try:
            value = float(input(提示信息))
            if value >= 0: # 假设时间不为负
                return value
            else:
                print('⚠️  请输入一个非负数。')
        except ValueError:
            print('⚠️  输入无效，请输入一个数字。')

def 获取用户输入():
    print('=== 请输入今日数据 ===')
    睡眠 = 验证用户输入('🌙 昨晚睡了几个小时: ')
    学习 = 验证用户输入('📚 今天Python学了几个小时: ')
    娱乐 = 验证用户输入('🎮 娱乐放松了几小时: ')
    运动 = 验证用户输入('💪 运动了多长时间（小时）: ')
    return [睡眠, 学习, 娱乐, 运动]

def 验证并获取输入():
    while True:
        输入列表 = 获取用户输入()
        总时间 = sum(输入列表)
        if 总时间 <= 24:
            return 输入列表
        else:
            print(f'⚠️  总时间 {总时间:.1f} ，超过24小时，请重新输入全天数据。\n')