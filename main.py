# ===== 本地应用导入 =====
from core.input_handler import 验证并获取输入
from core.analyzer import 智能分析, 综合评估, 能量守恒检查
from core.data_manager import 计算时间, 保存今日数据, 读取历史数据

# 在 main()函数内部，用清晰的步骤注释，描述“做什么”而非“怎么做”，代码会告诉我们怎么做。
def main():
    '''时间管理系统的主流程控制器'''
    # 1. 获取并验证用户输入
    输入列表 = 验证并获取输入()
    
    # 2. 计算核心数据，创建数据对象
    记录 = 计算时间(*输入列表) # 记录 是一个 每日记录 对象
    print(f'⏳ 时间总账：用了{记录.总时间:.1f} 小时，还剩{记录.剩余时间:.1f} 小时')
    
    # 3. 生成各类分析报告
    智能分析(记录)
    综合评估(记录)
    能量守恒检查(记录.剩余时间)
    
    # 4. 持久化数据
    保存今日数据(记录)
    
    # 5. 可选，查看历史
    查看历史 = input('\n是否查看历史记录? (y/n): ').lower()
    if 查看历史 == 'y':
        读取历史数据()

if __name__ == '__main__':
    main()